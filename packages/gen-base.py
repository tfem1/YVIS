#!/usr/bin/env python3
"""Generate the YONEBUILD recipes of the YVIS base from the LFS book.

    packages/gen-base.py --out DIR [--sources DIR] [--build-id ID]

One recipe per package of chapter 8, plus:
  filesystem            the layout and essential files of chapters 4 and 7
  yvis-base-files       system/rootfs/ (chapter 9, YVIS's way)
  yvis-initramfs-tools  system/initramfs/
  base                  a meta package that depends on all of them

The commands are the book's, as lfs/build.sh runs them (lfs/skip, lfs/edits),
turned into a DESTDIR installation the way jhalfs does it for package
managers: installation commands write to $PKGDIR, and every absolute path a
command writes to is prefixed with $PKGDIR. What is not a package's content
(setting up accounts, enabling services, regenerating caches) is left to
hooks or to the assembly of the system (packages/assemble.sh).

packages/base/skip lists more blocks to leave out than the build does;
packages/base/overrides/<name>.sh replaces a package's commands and
<name>.post adds commands after them.
"""
import argparse
import os
import re
import subprocess
import sys
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
LFS = os.path.join(REPO, "lfs")
BASE = os.path.join(HERE, "base")

# Commands that set up the running system, not package content.
SYSTEM_COMMANDS = {
    "ldconfig", "systemctl", "systemd-machine-id-setup", "pwconv", "grpconv",
    "groupadd", "passwd", "install-info", "mandb", "udevadm",
    "systemd-hwdb", "exec",
}
# Sections that are not packages.
NOT_PACKAGES = {"ch-system-pkgmgt", "ch-system-stripping", "ch-system-cleanup"}
# Absolute paths that are never redirected to $PKGDIR.
SYSTEM_PATHS = ("/dev/", "/proc/", "/sys/")
# Words after which the next word is a command name.
COMMAND_STARTERS = {";", "&&", "||", "|", "(", "{", "do", "then", "else", "elif", "!", "&"}

# Directories created before the book's commands so that `cp x /etc` and
# `cat > /etc/x` work as on a full system; removed again if left empty.
PRELUDE_DIRS = [
    "etc", "usr/bin", "usr/sbin", "usr/lib", "usr/lib/pkgconfig", "usr/include",
    "usr/libexec", "usr/share/doc", "usr/share/info", "usr/share/locale",
    "usr/share/man/man1", "usr/share/man/man2", "usr/share/man/man3",
    "usr/share/man/man4", "usr/share/man/man5", "usr/share/man/man6",
    "usr/share/man/man7", "usr/share/man/man8", "var/lib",
    "usr/lib/locale", "usr/lib/bfd-plugins",
]

PRELUDE = r'''# --- YVIS: install into $PKGDIR, a tree with the layout of the system
yvis_prelude() {
  local d
  for d in @DIRS@; do mkdir -p "$PKGDIR/$d"; done
  for d in bin lib sbin; do ln -sfn "usr/$d" "$PKGDIR/$d"; done
}

# --- YVIS: what the book does once for the whole system (8.84 stripping,
# 8.85 cleanup) is done for each package; caches regenerated by hooks are
# not package content.
yvis_finish() {
  local d f
  cd "$PKGDIR"
  for d in bin lib sbin; do
    [ -L "$d" ] || { echo "yvis: /$d is no longer a link to usr/$d" >&2; return 1; }
    rm "$d"
  done
  rm -f usr/share/info/dir
  find usr/lib usr/libexec -name '*.la' -delete 2> /dev/null || true
  # the files 8.84 strips: programs, shared and static libraries
  while IFS= read -r -d '' f; do
    strip --strip-unneeded "$f" 2> /dev/null || true
  done < <(find usr/bin usr/sbin usr/libexec -type f -print0 2> /dev/null
           find usr/lib -type f \( -name '*.so*' -o -name '*.a' \) ! -name '*.dbg' -print0 2> /dev/null)
  for d in $(printf '%s\n' @DIRS@ | sort -r); do rmdir "$d" 2> /dev/null || true; done
  rmdir usr/share/man usr/share usr 2> /dev/null || true
}
'''


def die(msg):
    sys.exit(f"gen-base: {msg}")


# ------------------------------------------------------------ shell words

class Word:
    """A shell word with what it starts with, for the rewriting rules."""

    def __init__(self, text, start, end, quoted_start):
        self.text, self.start, self.end = text, start, end
        self.quoted_start = quoted_start  # starts with a quote


def scan(line, continued):
    """Split a physical line into words and operators, quotes respected.

    Returns (tokens, unterminated): tokens are Word objects or operator
    strings with positions; a quote left open makes the next line part of
    the same word (rare in the book; such lines are left untouched)."""
    tokens = []
    i, n = 0, len(line)
    while i < n:
        c = line[i]
        if c in " \t":
            i += 1
            continue
        if c == "#" and (i == 0 or line[i - 1] in " \t"):
            break  # comment
        for op in ("&&", "||", ">>", ";;", ">", "<", "|", ";", "(", ")", "&"):
            if line.startswith(op, i):
                # "2>" and "&>" are redirections too
                tokens.append((op, i, i + len(op)))
                i += len(op)
                break
        else:
            start = i
            depth = 0
            quote = None
            while i < n:
                c = line[i]
                if quote:
                    if c == "\\" and quote == '"':
                        i += 2
                        continue
                    if c == quote:
                        quote = None
                    i += 1
                    continue
                if c in "'\"`":
                    quote = c
                    i += 1
                    continue
                if c == "\\":
                    i += 2
                    continue
                if line.startswith("$(", i):
                    depth += 1
                    i += 2
                    continue
                if c == ")" and depth:
                    depth -= 1
                    i += 1
                    continue
                if depth == 0 and (c in " \t;|&<>" or (c == ")" and not depth)):
                    break
                i += 1
            if quote:
                return tokens, True
            text = line[start:i]
            # a redirection number glued to the operator: 2>file
            tokens.append(Word(text, start, i, text[:1] in "'\"`"))
    return tokens, False


def is_target_path(word):
    t = word.text
    return (not word.quoted_start and t.startswith("/")
            and not t.startswith(SYSTEM_PATHS) and t != "/dev/null")


def ln_target_index(words):
    """Index (in words) of the target of `ln -s` without -r, else None."""
    opts = [w.text for w in words[1:] if w.text.startswith("-")]
    symbolic = any(o == "--symbolic" or (not o.startswith("--") and "s" in o) for o in opts)
    relative = any(o == "--relative" or (not o.startswith("--") and "r" in o) for o in opts)
    if not symbolic or relative:
        return None
    for k, w in enumerate(words[1:], 1):
        if not w.text.startswith("-"):
            return k
    return None


def rewrite_line(line, continued, cmd_state):
    """Rewrite one physical line. cmd_state carries the command being
    continued from the previous line (its name and words so far)."""
    tokens, open_quote = scan(line, continued)
    if open_quote:
        return line, None
    edits = []  # (start, end, replacement)
    # split into simple commands
    commands = []
    cur = cmd_state["words"] if continued and cmd_state else []
    cur_redirect = None
    for t in tokens:
        if isinstance(t, tuple):
            op = t[0]
            if op in (">", ">>"):
                cur_redirect = ">"
            elif op == "<":
                cur_redirect = "<"
            elif op in (";", "&&", "||", "|", "(", ")", "&", ";;"):
                commands.append(cur)
                cur = []
            continue
        if cur_redirect:
            if cur_redirect == ">" and is_target_path(t):
                edits.append((t.start, t.start, '"$PKGDIR"'))
            cur_redirect = None
            continue
        if not cur and t.text in COMMAND_STARTERS:
            continue
        cur.append(t)
    commands.append(cur)

    new_state = {"words": cur} if line.rstrip().endswith("\\") else None
    first_on_line = {id(w) for w in (t for t in tokens if isinstance(t, Word))}
    drop = False
    for words in commands:
        if not words:
            continue
        # skip leading assignments and keywords
        k = 0
        while k < len(words) and re.match(r"^[A-Za-z_][A-Za-z0-9_]*=", words[k].text):
            k += 1
        if k < len(words) and words[k].text in ("for", "case", "while", "if"):
            # `for x in <words>`: the list may name paths to write to
            for w in words[k + 1:]:
                if is_target_path(w) and id(w) in first_on_line:
                    edits.append((w.start, w.start, '"$PKGDIR"'))
            continue
        if k >= len(words):
            # only assignments: `ZONEINFO=/usr/share/zoneinfo` names where to write
            for w in words:
                name_, _, value = w.text.partition("=")
                if value.startswith("/") and not value.startswith(SYSTEM_PATHS) and id(w) in first_on_line:
                    at = w.start + len(name_) + 1
                    edits.append((at, at, '"$PKGDIR"'))
            continue
        name = os.path.basename(words[k].text)
        args = words[k:]
        if name in SYSTEM_COMMANDS and id(words[k]) in first_on_line:
            drop = True
            continue
        keep = ln_target_index(args) if name == "ln" else None
        for idx, w in enumerate(args[1:], 1):
            if id(w) not in first_on_line:
                continue  # rewritten on its own line already
            if idx == keep:
                continue
            if is_target_path(w):
                edits.append((w.start, w.start, '"$PKGDIR"'))
            elif w.text.startswith("$(gcc -print-"):
                edits.append((w.start, w.start, '"$PKGDIR"'))
        if id(args[0]) not in first_on_line:
            continue
        targets = [w.text for w in args[1:] if not w.text.startswith("-") and "=" not in w.text]
        texts = [w.text for w in args[1:]]
        if name == "make" and any("install" in t for t in targets) \
                and not any(t.startswith("DESTDIR=") for t in texts):
            last = args[-1]
            edits.append((last.end, last.end, ' DESTDIR="$PKGDIR"'))
        elif name in ("ninja", "meson") and "install" in texts:
            edits.append((args[0].start, args[0].start, 'DESTDIR="$PKGDIR" '))
        elif name in ("pip3", "pip") and texts[:1] == ["install"]:
            edits.append((args[1].end, args[1].end, ' --root="$PKGDIR" --ignore-installed --no-deps'))
        elif name == "localedef":
            edits.append((args[0].end, args[0].end, ' --prefix="$PKGDIR"'))
    if drop:
        return "# YVIS: not package content (system setup): " + line.strip(), new_state
    for start, end, rep in sorted(edits, reverse=True):
        line = line[:start] + rep + line[end:]
    return line, new_state


HEREDOC = re.compile(r"""<<-?\s*(['"]?)(\w+)\1""")


def rewrite(script):
    """Rewrite a whole script: heredoc bodies are file contents, untouched."""
    out = []
    lines = script.split("\n")
    here = None
    state = None
    for line in lines:
        if here:
            out.append(line)
            if line.strip() == here:
                here = None
            continue
        if line.lstrip().startswith("#") or not line.strip():
            out.append(line)
            state = None if not line.strip() else state
            continue
        continued = state is not None
        new, state = rewrite_line(line, continued, state)
        out.append(new)
        m = HEREDOC.search(line)
        if m:
            here = m.group(2)
    return "\n".join(out)


# ------------------------------------------------------------ book data

def book_commands(sid, script, extra_skip):
    """The book's commands as lfs/build.sh runs them (skip, edits)."""
    cmd = ('HERE="$1"; die() { echo "$*" >&2; exit 1; }; . "$1/book-commands.sh"; '
           'book_commands "$2" "$3" "$4"')
    r = subprocess.run(["bash", "-c", cmd, "-", LFS, sid, script, extra_skip],
                       capture_output=True, text=True)
    if r.returncode != 0:
        die(f"{sid}: {r.stderr.strip()}")
    return r.stdout


def sources_index():
    urls = {}
    for line in open(os.path.join(LFS, "wget-list")):
        line = line.strip()
        if line and not line.startswith("#"):
            urls[line.rsplit("/", 1)[-1]] = line
    sums = {}
    for line in open(os.path.join(LFS, "sources.sha256")):
        parts = line.split()
        if len(parts) == 2:
            sums[parts[1]] = parts[0]
    return urls, sums


def topdir(tarball, sources):
    """Directory the tarball unpacks to."""
    path = os.path.join(sources, tarball) if sources else None
    if path and os.path.exists(path):
        with tarfile.open(path) as t:
            for m in t:
                return m.name.lstrip("./").split("/")[0]
    name = re.sub(r"\.(tar\.\w+|tgz)$", "", tarball)
    return re.sub(r"-src$", "", name)


def version_of(title):
    m = re.search(r"-([0-9][0-9A-Za-z.]*)$", title.strip())
    return m.group(1) if m else None


def package_name(sid):
    return sid.replace("ch-system-", "").replace("ch-tools-", "").lower()


# ------------------------------------------------------------ recipes

def recipe_text(name, version, desc, url, sources, urls, sums, noextract, body,
                depends, release=1, backup=()):
    lines = [f"# Generated by packages/gen-base.py from the LFS book -- do not edit;",
             f"# use packages/base/skip and packages/base/overrides/.",
             f"name = {name}", f"version = {version}", f"release = {release}",
             f"desc = {desc}"]
    if url:
        lines.append(f"url = {url}")
    if depends:
        lines.append("depends = " + " ".join(depends))
    for b in backup:
        lines.append(f"backup = {b}")
    for s in sources:
        if s not in urls or s not in sums:
            die(f"{name}: source {s} is not in lfs/wget-list and lfs/sources.sha256")
        lines.append(f"source = {urls[s]}")
        lines.append(f"sha256 = {sums[s]}")
    if noextract:
        lines.append("noextract = " + " ".join(noextract))
    lines += ["", "@package", body.rstrip("\n"), ""]
    return "\n".join(lines)


def extra_sources(script, main, urls):
    found = []
    for m in re.finditer(r"\.\./(?:\.\./)?([A-Za-z0-9][\w.+-]*)", script):
        f = m.group(1)
        if f in urls and f != main and f not in found:
            found.append(f)
    return found


def apply_edits(name, text, edits_file):
    """packages/base/edits: <package><TAB><sed -E expression>, applied to
    the rewritten commands; an edit that changes nothing is an error."""
    if not os.path.exists(edits_file):
        return text
    for line in open(edits_file):
        if line.startswith("#") or "\t" not in line:
            continue
        pkg, expr = line.rstrip("\n").split("\t", 1)
        if pkg != name:
            continue
        r = subprocess.run(["sed", "-E", expr], input=text, capture_output=True, text=True)
        if r.returncode != 0:
            die(f"packages/base/edits: {name}: {r.stderr.strip()}")
        if r.stdout == text:
            die(f"packages/base/edits: '{expr}' changes nothing in {name} (did the book change?)")
        text = r.stdout
    return text


def chapter8(sources, urls, sums, extra_skip, overrides):
    recipes = {}
    for line in open(os.path.join(LFS, "book", "sections.tsv")):
        if line.startswith("#") or not line.strip():
            continue
        ch, order, sid, tb, title = line.rstrip("\n").split("\t")
        if ch != "ch08" or sid in NOT_PACKAGES or tb == "-":
            continue
        name = package_name(sid)
        script = os.path.join(LFS, "book", ch, f"{order}-{sid}.sh")
        header = open(script).read()
        url = (re.search(r"^# source: (\S+)", header, re.M) or [None, None])[1]
        version = version_of(title) or die(f"{sid}: no version in '{title}'")
        override = os.path.join(overrides, f"{name}.sh")
        if os.path.exists(override):
            commands = open(override).read()
        else:
            commands = book_commands(sid, script, extra_skip)
        post = os.path.join(overrides, f"{name}.post")
        if os.path.exists(post):
            commands += "\n# --- YVIS: packages/base/overrides/" + f"{name}.post\n" + open(post).read()
        extras = extra_sources(commands, tb, urls)
        rewritten = apply_edits(name, rewrite(commands), os.path.join(BASE, "edits"))
        body = "\n".join([
            PRELUDE.replace("@DIRS@", " ".join(PRELUDE_DIRS)),
            f'cd "$SRCDIR/{topdir(tb, sources)}"',
            "yvis_prelude",
            "",
            rewritten.strip("\n"),
            "",
            "yvis_finish",
        ])
        title_clean = re.sub(r"^\d+\.\d+\s+", "", title)
        recipes[name] = recipe_text(
            name, version, f"{title_clean} (LFS 13.1-systemd, chapter 8)", url,
            [tb] + extras, urls, sums,
            [e for e in extras if re.search(r"\.(tar\.\w+|tgz)$", e)],
            body, ["filesystem"], backup=["etc/"])
    return recipes


def embed_tree(src, dest_prefix=""):
    """Commands that recreate the files of a directory in $PKGDIR."""
    out = []
    for base, dirs, files in sorted(os.walk(src)):
        dirs.sort()
        for f in sorted(files):
            p = os.path.join(base, f)
            rel = os.path.join(dest_prefix, os.path.relpath(p, src))
            mode = "755" if os.access(p, os.X_OK) else "644"
            text = open(p).read()
            if "YVIS_EOF" in text:
                die(f"{p} contains the heredoc delimiter")
            if not text.endswith("\n"):
                die(f"{p} does not end with a newline")
            out.append(f'install -d "$PKGDIR/{os.path.dirname(rel)}"')
            out.append(f"cat > \"$PKGDIR/{rel}\" <<'YVIS_EOF'")
            out.append(text.rstrip("\n"))
            out.append("YVIS_EOF")
            out.append(f'chmod {mode} "$PKGDIR/{rel}"')
    return "\n".join(out)


def yvis_recipes(build_id):
    recipes = {}
    rootfs = os.path.join(REPO, "system", "rootfs")
    version = re.search(r'^VERSION_ID="?([^"\n]+)', open(os.path.join(rootfs, "usr/lib/os-release")).read(), re.M)[1]
    body = "\n".join([
        "# system/rootfs: chapter 9 the YVIS way (see lfs/yvis/ch09)",
        embed_tree(rootfs),
        f'sed -i "s/@BUILD_ID@/{build_id}/" "$PKGDIR/usr/lib/os-release"',
        'ln -s ../usr/lib/os-release "$PKGDIR/etc/os-release"',
        "# one identifier per installed machine, created at its first boot",
        ': > "$PKGDIR/etc/machine-id"',
        'chmod 444 "$PKGDIR/etc/machine-id"',
    ])
    backup = ["etc/"]
    recipes["yvis-base-files"] = recipe_text(
        "yvis-base-files", version, "YVIS system configuration: network, locale, console, identity",
        "https://github.com/tfem1/YVIS", [], {}, {}, [], body, ["filesystem"], backup=backup)

    initramfs = os.path.join(REPO, "system", "initramfs")
    body = "\n".join([
        "# system/initramfs: the initramfs builder and what it puts in the image",
        embed_tree(os.path.join(initramfs, "live"), "usr/share/yvis/initramfs/live"),
        'install -d "$PKGDIR/usr/sbin" "$PKGDIR/usr/share/yvis/initramfs"',
        "cat > \"$PKGDIR/usr/sbin/yvis-mkinitramfs\" <<'YVIS_EOF'",
        open(os.path.join(initramfs, "yvis-mkinitramfs")).read().rstrip("\n"),
        "YVIS_EOF",
        'chmod 755 "$PKGDIR/usr/sbin/yvis-mkinitramfs"',
        "cat > \"$PKGDIR/usr/share/yvis/initramfs/init\" <<'YVIS_EOF'",
        open(os.path.join(initramfs, "init")).read().rstrip("\n"),
        "YVIS_EOF",
        'chmod 755 "$PKGDIR/usr/share/yvis/initramfs/init"',
    ])
    recipes["yvis-initramfs-tools"] = recipe_text(
        "yvis-initramfs-tools", version, "Builds the YVIS initramfs (installed system or live medium)",
        "https://github.com/tfem1/YVIS",
        [], {}, {}, [], body, ["filesystem", "python", "kmod", "systemd", "util-linux", "bash", "zstd"])
    return recipes


def filesystem_recipe(extra_skip):
    """Chapter 4's layout and chapter 7's directories and files."""
    parts = ["# chapter 4: the merged /usr layout",
             'install -d "$PKGDIR"/{etc,var} "$PKGDIR"/usr/{bin,lib,sbin} "$PKGDIR/lib64"',
             'for i in bin lib sbin; do ln -s usr/$i "$PKGDIR/$i"; done',
             "# 7.3: mount points of the virtual kernel file systems",
             'install -d "$PKGDIR"/{dev,proc,sys,run}']
    for line in open(os.path.join(LFS, "book", "sections.tsv")):
        f = line.rstrip("\n").split("\t")
        if len(f) == 5 and f[2] in ("ch-tools-creatingdirs", "ch-tools-createfiles"):
            script = os.path.join(LFS, "book", f[0], f"{f[1]}-{f[2]}.sh")
            parts.append(f"# --- {f[4]}")
            parts.append(rewrite(book_commands(f[2], script, extra_skip)).strip("\n"))
    body = "\n".join(parts)
    # merged /usr: the links must not be followed while the tree is built
    body = body.replace('"$PKGDIR"/lib/firmware', '"$PKGDIR"/usr/lib/firmware')
    return recipe_text("filesystem", "13.1", "Directory layout, accounts and essential files (LFS 13.1, chapters 4 and 7)",
                       "https://www.linuxfromscratch.org/lfs/view/13.1-systemd/chapter07/creatingdirs.html",
                       [], {}, {}, [], body, [],
                       backup=["etc/"])


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", required=True)
    ap.add_argument("--sources", help="directory of the source tarballs (for their top directory)")
    ap.add_argument("--build-id", default="dev")
    a = ap.parse_args()
    urls, sums = sources_index()
    extra_skip = os.path.join(BASE, "skip")
    recipes = {"filesystem": filesystem_recipe(extra_skip)}
    recipes.update(chapter8(a.sources, urls, sums, extra_skip, os.path.join(BASE, "overrides")))
    recipes.update(yvis_recipes(a.build_id))
    names = list(recipes)
    recipes["base"] = recipe_text(
        "base", "13.1", "The YVIS base system", "https://github.com/tfem1/YVIS",
        [], {}, {}, [], "true", names)
    os.makedirs(a.out, exist_ok=True)
    order = names + ["base"]
    for name in order:
        d = os.path.join(a.out, name)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "YONEBUILD"), "w") as f:
            f.write(recipes[name])
    with open(os.path.join(a.out, "order"), "w") as f:
        f.write("\n".join(order) + "\n")
    print(f"{len(order)} recipes in {a.out}")


if __name__ == "__main__":
    main()
